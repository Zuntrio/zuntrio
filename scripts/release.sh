#!/bin/bash
# Release helper for Zuntrio maintainers.
#
#   scripts/release.sh prepare <version>   Bump project.yml on a release branch and open a pull request.
#   scripts/release.sh check <version>     Dry run: the same checks, tests, signed build and verification as
#                                          build, but no notarization and no GitHub release.
#   scripts/release.sh build <version>     On an up-to-date main: test, build, sign, notarize, staple,
#                                          verify, zip, and create a DRAFT GitHub release.
#
# <version> is X.Y.Z, X.Y.Z-beta.N or X.Y.Z-rc.N. The tag is v<version>. MARKETING_VERSION holds X.Y.Z,
# App/Sources/App/ReleaseInfo.swift the full version; the build number goes up by one with every prepare.
#
# Needs Xcode 27 or later, xcodegen, gh (signed in), a "Developer ID Application" identity in the
# keychain, and a notarytool keychain profile (xcrun notarytool store-credentials).
#
# Optional environment:
#   ZUNTRIO_NOTARY_PROFILE  notarytool keychain profile (default: zuntrio-notary)
#   ZUNTRIO_SIGN_IDENTITY   signing identity (default: the only Developer ID Application identity found)
#   ZUNTRIO_NOTES           release notes file for the draft (default: notes generated by GitHub)
#   ZUNTRIO_TAP_DIR         local clone of Zuntrio/homebrew-tap; the cask is bumped and committed there
#
# Nothing is published: the GitHub release stays a draft until a maintainer publishes it.
set -euo pipefail

REPO="Zuntrio/zuntrio"
PROFILE="${ZUNTRIO_NOTARY_PROFILE:-zuntrio-notary}"

cd "$(dirname "$0")/.."

die() { printf '\nError: %s\n' "$*" >&2; exit 1; }
step() { printf '\n==> %s\n' "$*"; }
usage() { sed -n '2,22p' "$0" | sed 's/^# \{0,1\}//'; exit 2; }

[ $# -eq 2 ] || usage
command=$1
version=$2
printf '%s' "$version" | grep -Eq '^[0-9]+\.[0-9]+\.[0-9]+(-(beta|rc)\.[0-9]+)?$' \
  || die "Version must look like 1.2.3, 1.2.3-beta.4 or 1.2.3-rc.1 (got '$version')."

base=${version%%-*}
tag="v$version"
title="Zuntrio $(printf '%s' "$version" | sed -e 's/-beta\./ beta /' -e 's/-rc\./ RC /')"
case $version in *-*) prerelease=yes ;; *) prerelease=no ;; esac

current_marketing=$(sed -n 's/^ *MARKETING_VERSION: "\(.*\)"$/\1/p' project.yml)
current_build=$(sed -n 's/^ *CURRENT_PROJECT_VERSION: "\(.*\)"$/\1/p' project.yml)
[ -n "$current_marketing" ] && [ -n "$current_build" ] || die "Couldn't read the version from project.yml."
release_info=App/Sources/App/ReleaseInfo.swift
current_release=$(sed -n 's/^ *static let version = "\(.*\)"$/\1/p' "$release_info")
[ -n "$current_release" ] || die "Couldn't read the version from $release_info."

for tool in git gh xcodegen; do
  command -v "$tool" >/dev/null 2>&1 || die "$tool is not installed."
done

require_clean_main() {
  [ "$(git rev-parse --abbrev-ref HEAD)" = main ] || die "Switch to main first."
  [ -z "$(git status --porcelain)" ] || die "The working tree has uncommitted changes."
  git fetch -q origin
  [ "$(git rev-parse HEAD)" = "$(git rev-parse origin/main)" ] || die "main isn't in sync with origin/main. Pull first."
}

require_unreleased() {
  if git ls-remote --exit-code --tags origin "refs/tags/$tag" >/dev/null 2>&1; then
    die "The tag $tag already exists."
  fi
  if gh release view "$tag" -R "$REPO" >/dev/null 2>&1; then
    die "A release (or draft) for $tag already exists."
  fi
}

prepare() {
  require_clean_main
  require_unreleased
  local build=$((current_build + 1))
  local branch="release/$version"

  step "Bumping to $version (MARKETING_VERSION $base, build $build) on $branch"
  git switch -q -c "$branch"
  sed -i '' \
    -e "s/^\( *MARKETING_VERSION: \)\"$current_marketing\"$/\1\"$base\"/" \
    -e "s/^\( *CURRENT_PROJECT_VERSION: \)\"$current_build\"$/\1\"$build\"/" \
    project.yml
  sed -i '' -e "s/^\( *static let version = \)\".*\"$/\1\"$version\"/" "$release_info"
  git diff --stat
  git commit -q -am "Bump version to $version (build $build)"

  step "Pushing $branch and opening a pull request"
  git push -q -u origin "$branch"
  gh pr create -R "$REPO" --base main --head "$branch" --title "Prepare $version" \
    --body "Bumps MARKETING_VERSION to $base, the build number to $build and ReleaseInfo.version to $version."

  printf '\nNext: merge the pull request once CI passes, update main, then run:\n  scripts/release.sh build %s\n' "$version"
}

build() {
  local dry_run=${1:-no}
  require_clean_main
  require_unreleased
  [ "$current_marketing" = "$base" ] \
    || die "project.yml has MARKETING_VERSION $current_marketing, expected $base. Run: scripts/release.sh prepare $version"
  [ "$current_release" = "$version" ] \
    || die "$release_info has version $current_release, expected $version. Run: scripts/release.sh prepare $version"

  local xcode_major
  xcode_major=$(xcodebuild -version | awk 'NR == 1 { split($2, v, "."); print v[1] }')
  [ "${xcode_major:-0}" -ge 27 ] || die "Releases must be built with Xcode 27 or later (found $(xcodebuild -version | head -1))."

  local identity="${ZUNTRIO_SIGN_IDENTITY:-}"
  if [ -z "$identity" ]; then
    local found
    found=$(security find-identity -v -p codesigning | sed -n 's/.*"\(Developer ID Application: .*\)"$/\1/p' | sort -u)
    [ -n "$found" ] || die "No valid Developer ID Application identity in the keychain."
    [ "$(printf '%s\n' "$found" | wc -l | tr -d ' ')" = 1 ] || die "Several Developer ID identities found. Set ZUNTRIO_SIGN_IDENTITY."
    identity=$found
  fi
  local team
  team=$(printf '%s' "$identity" | sed -n 's/.*(\([A-Z0-9]\{10\}\))$/\1/p')
  [ -n "$team" ] || die "Couldn't read the team ID from '$identity'."
  xcrun notarytool history --keychain-profile "$PROFILE" >/dev/null 2>&1 \
    || die "The notarytool profile '$PROFILE' doesn't work. Create it with: xcrun notarytool store-credentials $PROFILE ..."

  local commit
  commit=$(git rev-parse HEAD)
  printf 'Version:  %s (build %s)\nCommit:   %s\nIdentity: %s\n' "$version" "$current_build" "$commit" "$identity"

  step "Running tests"
  swift test --package-path ZuntrioCore --quiet
  xcodegen generate --quiet
  xcodebuild -project Zuntrio.xcodeproj -scheme Zuntrio -destination 'platform=macOS' \
    -derivedDataPath build/DerivedData -quiet test

  step "Building the Universal Release"
  rm -rf build/release build/release-out
  xcodebuild -project Zuntrio.xcodeproj -scheme Zuntrio -configuration Release \
    -destination 'generic/platform=macOS' -derivedDataPath build/release \
    CODE_SIGN_IDENTITY="$identity" DEVELOPMENT_TEAM="$team" OTHER_CODE_SIGN_FLAGS=--timestamp \
    -quiet build
  local app=build/release/Build/Products/Release/Zuntrio.app
  local binary="$app/Contents/MacOS/Zuntrio"
  local out=build/release-out
  mkdir -p "$out"

  step "Checking the build"
  codesign --verify --strict "$app" || die "codesign --verify failed."
  local info
  info=$(codesign -dv "$app" 2>&1)
  [ "$(printf '%s\n' "$info" | sed -n 's/^TeamIdentifier=//p')" = "$team" ] || die "The app isn't signed by team $team."
  case $info in *"Timestamp="*) ;; *) die "The signature has no secure timestamp." ;; esac
  case $info in *"(runtime)"*) ;; *) die "The hardened runtime is off." ;; esac
  [ -z "$(codesign -d --entitlements :- "$app" 2>/dev/null)" ] || die "The app has entitlements; Release must have none."
  local archs
  archs=$(lipo -archs "$binary")
  case " $archs " in *" arm64 "*) ;; *) die "arm64 slice missing (found: $archs)." ;; esac
  case " $archs " in *" x86_64 "*) ;; *) die "x86_64 slice missing (found: $archs)." ;; esac
  [ "$(strings "$binary" | grep -c -- '--poc-' || true)" = 0 ] || die "The debug test harness is in the Release binary."
  local plist="$app/Contents/Info.plist"
  [ "$(/usr/libexec/PlistBuddy -c 'Print CFBundleShortVersionString' "$plist")" = "$base" ] || die "CFBundleShortVersionString isn't $base."
  [ "$(/usr/libexec/PlistBuddy -c 'Print CFBundleVersion' "$plist")" = "$current_build" ] || die "CFBundleVersion isn't $current_build."
  echo "Signed by $team, timestamped, hardened runtime, no entitlements, $archs, no debug harness, version $base ($current_build)."

  if [ "$dry_run" = yes ]; then
    printf '\nCheck passed. Nothing was uploaded. The signed (not notarized) app is in %s.\n' "$app"
    return
  fi

  step "Notarizing (this usually takes a few minutes)"
  ditto -c -k --keepParent "$app" "$out/notarize.zip"
  local result accepted
  result=$(xcrun notarytool submit "$out/notarize.zip" --keychain-profile "$PROFILE" --wait 2>&1) || true
  printf '%s\n' "$result" | tail -3
  rm -f "$out/notarize.zip"
  case $result in *"status: Accepted"*) accepted=yes ;; *) accepted=no ;; esac
  if [ "$accepted" = no ]; then
    local id
    id=$(printf '%s\n' "$result" | sed -n 's/^ *id: //p' | head -1)
    [ -n "$id" ] && xcrun notarytool log "$id" --keychain-profile "$PROFILE" >&2 || true
    die "Notarization wasn't accepted."
  fi

  step "Stapling and checking Gatekeeper"
  xcrun stapler staple -q "$app"
  xcrun stapler validate -q "$app" || die "stapler validate failed."
  local gatekeeper
  gatekeeper=$(spctl -a -vv -t exec "$app" 2>&1) || die "Gatekeeper rejects the app: $gatekeeper"
  case $gatekeeper in *"source=Notarized Developer ID"*) ;; *) die "Gatekeeper doesn't see a notarized Developer ID app: $gatekeeper" ;; esac
  echo "Stapled; Gatekeeper: accepted, Notarized Developer ID."

  step "Packaging"
  ditto -c -k --keepParent "$app" "$out/Zuntrio.zip"
  (cd "$out" && shasum -a 256 Zuntrio.zip > Zuntrio.zip.sha256)
  local sha
  sha=$(awk '{ print $1 }' "$out/Zuntrio.zip.sha256")
  echo "$out/Zuntrio.zip  SHA-256 $sha"

  step "Creating the draft GitHub release $tag"
  local args=(-R "$REPO" --draft --target "$commit" --title "$title")
  [ "$prerelease" = yes ] && args+=(--prerelease)
  if [ -n "${ZUNTRIO_NOTES:-}" ]; then
    [ -f "$ZUNTRIO_NOTES" ] || die "ZUNTRIO_NOTES points to a missing file: $ZUNTRIO_NOTES"
    args+=(--notes-file "$ZUNTRIO_NOTES")
  else
    args+=(--generate-notes)
  fi
  gh release create "$tag" "${args[@]}" "$out/Zuntrio.zip" "$out/Zuntrio.zip.sha256"

  if [ -n "${ZUNTRIO_TAP_DIR:-}" ]; then
    step "Bumping the Homebrew cask in $ZUNTRIO_TAP_DIR (committed, not pushed)"
    local cask="$ZUNTRIO_TAP_DIR/Casks/zuntrio.rb"
    [ -f "$cask" ] || die "No cask at $cask."
    sed -i '' -e "s/^  version \".*\"$/  version \"$version\"/" -e "s/^  sha256 \".*\"$/  sha256 \"$sha\"/" "$cask"
    git -C "$ZUNTRIO_TAP_DIR" commit -q -am "Update Zuntrio to $version"
    git -C "$ZUNTRIO_TAP_DIR" log --oneline -1
  fi

  cat <<EOF

Done. Nothing is public yet.
  1. Review the draft release on GitHub and publish it. The tag $tag is created on $commit.
  2. After publishing, push the Homebrew cask${ZUNTRIO_TAP_DIR:+ (already bumped in $ZUNTRIO_TAP_DIR)}: version "$version", sha256 "$sha".
EOF
}

case $command in
  prepare) prepare ;;
  check) build yes ;;
  build) build ;;
  *) usage ;;
esac
